#!/usr/bin/env python3
"""Bundle robot/src/*.py into a single main.py for upload via mBlock.

All modules end up in one namespace, so:
- imports between local modules are removed,
- top-level names must be unique across modules (checked here).

With --config the given config.py is inlined at the top. Without it, the bundle
keeps `from config import ...` so the simulator can provide its own config module.

Usage:
    python3 robot/tools/bundle.py [--config robot/config.py] [--out robot/dist/main.py]
"""

import argparse
import ast
import io
import pathlib
import sys
import tokenize

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src"

# Dependency order: every module only uses names from modules above it.
MODULES = ["compat", "hw", "sense", "ui", "events", "mqtt", "net", "skills", "calib", "reflexes", "loop", "main"]


def top_level_names(tree):
    names = []
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
            names.append(node.name)
        elif isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name):
                    names.append(t.id)
    return names


def strip_local_imports(source, local):
    """Remove import statements that refer to local modules (by line range)."""
    tree = ast.parse(source)
    drop = set()
    for node in tree.body:
        mod = None
        if isinstance(node, ast.ImportFrom) and node.level == 0:
            mod = node.module
        elif isinstance(node, ast.Import) and len(node.names) == 1:
            mod = node.names[0].name
        if mod in local:
            drop.update(range(node.lineno, node.end_lineno + 1))
    lines = source.splitlines()
    kept = [line for i, line in enumerate(lines, start=1) if i not in drop]
    return "\n".join(kept).strip() + "\n", tree


def strip_docstrings(source):
    """Remove docstrings of the module, classes and functions (not a sole statement)."""
    tree = ast.parse(source)
    drop = set()
    for node in ast.walk(tree):
        if not isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef)):
            continue
        body = node.body
        if len(body) > 1 and isinstance(body[0], ast.Expr) and isinstance(body[0].value, ast.Constant) \
                and isinstance(body[0].value.value, str):
            drop.update(range(body[0].lineno, body[0].end_lineno + 1))
    lines = source.splitlines()
    return "\n".join(line for i, line in enumerate(lines, start=1) if i not in drop) + "\n"


def strip_comments(source):
    """Remove comments and blank lines; the device does not need them.

    Uses the tokenizer, so a "#" inside a string is left alone.
    """
    lines = source.splitlines()
    cut = {}  # line number -> column where a comment starts
    for tok in tokenize.generate_tokens(io.StringIO(source).readline):
        if tok.type == tokenize.COMMENT:
            cut[tok.start[0]] = tok.start[1]
    out = []
    for i, line in enumerate(lines, start=1):
        if i in cut:
            line = line[:cut[i]].rstrip()
        if line.strip():
            out.append(line)
    return "\n".join(out) + "\n"


def compact_indent(source):
    """One space per indentation level instead of four; the device does not care.

    Lines inside multi-line strings are left alone. Continuation lines inside
    brackets may lose alignment, which Python ignores.
    """
    protected = set()
    for tok in tokenize.generate_tokens(io.StringIO(source).readline):
        if tok.type == tokenize.STRING and tok.start[0] != tok.end[0]:
            protected.update(range(tok.start[0] + 1, tok.end[0] + 1))
    out = []
    for i, line in enumerate(source.splitlines(), start=1):
        if i not in protected:
            body = line.lstrip(" ")
            line = " " * ((len(line) - len(body)) // 4) + body
        out.append(line)
    return "\n".join(out) + "\n"


def bundle(config_path=None, strip=True):
    local = set(MODULES)
    parts = []
    seen = {}
    sources = []
    if config_path is not None:
        local.add("config")
        sources.append(("config", pathlib.Path(config_path)))
    sources += [(m, SRC / (m + ".py")) for m in MODULES]

    for name, path in sources:
        text, tree = strip_local_imports(path.read_text(encoding="utf-8"), local)
        if strip:
            text = compact_indent(strip_comments(strip_docstrings(text)))
        for n in top_level_names(tree):
            if n in seen:
                raise SystemExit("bundle: name %r defined in both %s and %s" % (n, seen[n], name))
            seen[n] = name
        parts.append("# ---- %s %s\n\n%s" % (name, "-" * (70 - len(name)), text))

    header = (
        "# mBot2 Agent Lab robot script. GENERATED by robot/tools/bundle.py, do not edit.\n"
        "# Sources: robot/src/. Config: %s.\n\n"
        % ("inlined" if config_path else "imported from module 'config'")
    )
    out = header + "\n\n".join(parts)
    compile(out, "main.py", "exec")
    return out


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--config", help="config.py to inline (contains secrets: never commit the result)")
    p.add_argument("--out", default=str(ROOT / "dist" / "main.py"))
    p.add_argument("--keep-comments", action="store_true", help="keep comments, e.g. to read the bundle")
    a = p.parse_args(argv)
    out = bundle(a.config, strip=not a.keep_comments)
    path = pathlib.Path(a.out)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(out, encoding="utf-8")
    print("bundle: wrote %s (%d bytes)" % (path, len(out.encode("utf-8"))), file=sys.stderr)


if __name__ == "__main__":
    main()
