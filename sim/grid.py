#!/usr/bin/env python3
"""Generate the line-grid field: the simulator world and the printable build plan.

This script and the world file it writes are the only places in the repo that
know the field's geometry. The robot script, server and web UI never do: they
only see tape colors under the sensor.

The grid: N x N junctions at a fixed pitch, black tape lines, and on every arm
of a junction two colored cross stripes under the line. The inner stripe (8 cm
from the junction) has the color of the junction's x, the outer one (12 cm) the
color of its y. Color code: red 0, yellow 1, green 2, blue 3.

Usage:
    python3 sim/grid.py                      # writes sim/worlds/gitter.json and docs/lab/feld/bauplan.svg
    python3 sim/grid.py --check              # fails if the committed files are out of date
"""

import argparse
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
WORLD_OUT = HERE / "worlds" / "gitter.json"
SVG_OUT = ROOT / "docs" / "lab" / "feld" / "bauplan.svg"

PITCH_CM = 30
NODES = 4
MARGIN_CM = 15
TAPE_CM = 1.9
STRIPE_X_CM = 8       # inner stripe centre from the junction centre: x digit
STRIPE_Y_CM = 12      # outer stripe centre: y digit
STRIPE_LEN_CM = 10    # across the line
CODE = ["red", "yellow", "green", "blue"]
REF_COLORS = ["white", "black", "red", "yellow", "green", "blue"]
REF_FIELD_CM = 5      # length of each reference field in driving direction
REF_WIDTH_CM = 10
# The reference strip is its own card next to the board: on the board, the
# stripes sticking out of the frame line leave no room for it.
REF_X_CM = 45         # driven along +x
REF_Y_CM = -11        # centre line, 6 cm below the board edge

SVG_COLORS = {"black": "#16181D", "red": "#D7263D", "yellow": "#F2C14E", "green": "#3BA55C",
              "blue": "#5DADE2", "white": "#FFFFFF"}


def node_xy(i, j):
    return MARGIN_CM + i * PITCH_CM, MARGIN_CM + j * PITCH_CM


def r1(v):
    return round(v, 2)


def band(x1, y1, x2, y2, width, color, layer):
    return {"from": [r1(x1), r1(y1)], "to": [r1(x2), r1(y2)], "width": width, "color": color, "layer": layer}


def build():
    size = 2 * MARGIN_CM + (NODES - 1) * PITCH_CM
    bands = []
    half = TAPE_CM / 2
    # Cross stripes on every arm that leads to a neighbour (the frame has no stubs).
    for i in range(NODES):
        for j in range(NODES):
            cx, cy = node_xy(i, j)
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                if not (0 <= i + dx < NODES and 0 <= j + dy < NODES):
                    continue
                for dist, digit in ((STRIPE_X_CM, i), (STRIPE_Y_CM, j)):
                    mx, my = cx + dx * dist, cy + dy * dist
                    # Perpendicular to the arm, centred on the line.
                    px, py = -dy * STRIPE_LEN_CM / 2, dx * STRIPE_LEN_CM / 2
                    bands.append(band(mx - px, my - py, mx + px, my + py, TAPE_CM, CODE[digit], 0))
    # Black lines on top, continuous across the stripes, closed frame.
    first, last = node_xy(0, 0)[0] - half, node_xy(NODES - 1, 0)[0] + half
    for k in range(NODES):
        x, y = node_xy(k, k)
        bands.append(band(first, y, last, y, TAPE_CM, "black", 1))
        bands.append(band(x, first, x, last, TAPE_CM, "black", 1))
    # Reference strip for color calibration, outside the frame.
    for k, color in enumerate(REF_COLORS):
        x = REF_X_CM + k * REF_FIELD_CM
        bands.append(band(x, REF_Y_CM, x + REF_FIELD_CM, REF_Y_CM, REF_WIDTH_CM, color, 0))

    # Start poses: axle on a junction, facing along a line (heading 0 = north).
    starts = []
    for (i, j), heading in (((0, 0), 90), ((3, 3), 270), ((0, 3), 180), ((3, 0), 0), ((1, 2), 90)):
        x, y = node_xy(i, j)
        starts.append({"x": x, "y": y, "heading": heading})
    probe_front = json.loads((HERE / "mbot2.json").read_text())["probe_front_cm"]
    return {
        "name": "gitter",
        "description": "Line grid %dx%d, pitch %d cm, with colored cross stripes. Generated by sim/grid.py, do not edit."
                       % (NODES, NODES, PITCH_CM),
        "floor": "white",
        "size": [size, size],
        "walls": [],
        "bands": bands,
        "starts": starts,
        # Sensor bar right before the white reference field, driving along +x.
        "reference_start": {"x": REF_X_CM - probe_front - 1, "y": REF_Y_CM, "heading": 90},
    }


def world_json(world):
    """Readable JSON: one band per line."""
    head = {k: v for k, v in world.items() if k != "bands"}
    lines = ["{"]
    for k, v in head.items():
        lines.append("  %s: %s," % (json.dumps(k), json.dumps(v, ensure_ascii=False)))
    lines.append('  "bands": [')
    lines.append(",\n".join("    " + json.dumps(b) for b in world["bands"]))
    lines.append("  ]")
    lines.append("}")
    return "\n".join(lines) + "\n"


def svg(world):
    """Build plan at scale 1:1 (1 user unit = 1 cm), y pointing up like the field."""
    w, h = world["size"]
    out = [
        '<svg xmlns="http://www.w3.org/2000/svg" width="%dcm" height="%dcm" viewBox="-2 -8 %d %d">' % (w + 4, h + 30, w + 4, h + 30),
        "<title>Bauplan Linienfeld</title>",
        '<text x="0" y="-4.5" font-family="sans-serif" font-size="2.5">Linienfeld: %d × %d Kreuzungen, '
        "Raster %d cm, Rand %d cm, Band %d mm</text>" % (NODES, NODES, PITCH_CM, MARGIN_CM, round(TAPE_CM * 10)),
        '<text x="0" y="-1.5" font-family="sans-serif" font-size="2" fill="#5F6368">Streifen quer unter der Linie, '
        "Mitte bei %d cm (x) und %d cm (y) ab Kreuzungsmitte, %d cm lang. "
        "Farbcode: Rot 0, Gelb 1, Grün 2, Blau 3.</text>" % (STRIPE_X_CM, STRIPE_Y_CM, STRIPE_LEN_CM),
        '<rect x="0" y="0" width="%s" height="%s" fill="#FFFFFF" stroke="#9AA0A6" stroke-width="0.2"/>' % (w, h),
        '<g transform="translate(0 %s) scale(1 -1)">' % h,
    ]
    for b in sorted(world["bands"], key=lambda b: b["layer"]):
        (x1, y1), (x2, y2) = b["from"], b["to"]
        hw = b["width"] / 2
        if x1 == x2:
            x, y, bw, bh = x1 - hw, min(y1, y2), b["width"], abs(y2 - y1)
        else:
            x, y, bw, bh = min(x1, x2), y1 - hw, abs(x2 - x1), b["width"]
        stroke = ' stroke="#9AA0A6" stroke-width="0.1"' if b["color"] == "white" else ""
        out.append('<rect x="%s" y="%s" width="%s" height="%s" fill="%s"%s/>' % (
            r1(x), r1(y), r1(bw), r1(bh), SVG_COLORS[b["color"]], stroke))
    out.append("</g>")
    for i in range(NODES):
        for j in range(NODES):
            x, y = node_xy(i, j)
            out.append('<text x="%s" y="%s" font-family="sans-serif" font-size="2" fill="#5F6368">(%d,%d)</text>' % (
                x + 1.6, h - y - 1.8, i, j))
    out.append('<text x="%s" y="%s" font-family="sans-serif" font-size="2" fill="#5F6368">Referenzstreifen auf eigenem '
               "Karton neben dem Feld: Weiß, Schwarz, Rot, Gelb, Grün, Blau, je %d × %d cm</text>"
               % (REF_X_CM, h - REF_Y_CM + REF_WIDTH_CM / 2 + 3, REF_FIELD_CM, REF_WIDTH_CM))
    out.append("</svg>")
    return "\n".join(out) + "\n"


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--check", action="store_true", help="only check that the committed files are current")
    a = p.parse_args(argv)
    world = build()
    files = {WORLD_OUT: world_json(world), SVG_OUT: svg(world)}
    stale = [str(path.relative_to(ROOT)) for path, text in files.items()
             if not path.exists() or path.read_text(encoding="utf-8") != text]
    if a.check:
        if stale:
            raise SystemExit("grid: out of date, run python3 sim/grid.py: %s" % ", ".join(stale))
        return
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print("grid: wrote %s" % path.relative_to(ROOT), file=sys.stderr)


if __name__ == "__main__":
    main()
